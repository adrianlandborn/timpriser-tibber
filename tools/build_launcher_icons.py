#!/usr/bin/env python3
"""Generate per-device launcher icons and the matching jungle entries.

Every product in manifest.xml declares its own launcher icon size. Shipping the
80x80 master to all of them makes the compiler scale it (and warn), and stores
more pixels than a 30x30 device needs. This script downsizes
resources/launcher_icon.png into resources-icons/<W>x<H>[-mode]/ and rewrites the block
between the "launcher icons" markers in monkey.jungle and monkey-release.jungle.

Usage: python3 tools/build_launcher_icons.py
Env:   CIQ_DEVICES_DIR overrides the SDK Devices folder.
"""
import json
import os
import re
import shutil
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
MASTER = ROOT / "resources" / "launcher_icon.png"
OUT = ROOT / "resources-icons"
JUNGLES = [ROOT / "monkey.jungle", ROOT / "monkey-release.jungle"]
BEGIN = "# --- launcher icons (generated by tools/build_launcher_icons.py) ---"
END = "# --- end launcher icons ---"
EXTRA = {"fenix847mm": ["resources-large"]}  # other per-device resource folders

devices_dir = Path(os.environ.get(
    "CIQ_DEVICES_DIR",
    Path.home() / "Library/Application Support/Garmin/ConnectIQ/Devices"))

products = re.findall(r'iq:product id="([^"]+)"', (ROOT / "manifest.xml").read_text())
sizes = {}
for product in products:
    path = devices_dir / product / "compiler.json"
    if not path.exists():
        sys.exit(f"missing device definition: {path}")
    info = json.loads(path.read_text())
    icon = info["launcherIcon"]
    if info["bitsPerPixel"] <= 8:
        mode = "p64"  # 64-colour screen: palette-exact colours, hard edges
    elif not info.get("alphaBlendingSupport"):
        mode = "flat"  # no alpha blending: hard edges
    else:
        mode = "full"
    sizes.setdefault((icon["width"], icon["height"], mode), []).append(product)

master = Image.open(MASTER).convert("RGBA")
if max(max(size[:2]) for size in sizes) > master.width:
    sys.exit(f"master icon ({master.width}px) is smaller than the largest size")

LEVELS = (0, 85, 170, 255)  # the 2 bits per channel of 64-colour screens


def snap(value):
    return min(LEVELS, key=lambda level: abs(level - value))


def render(width, height, mode):
    """Fit the square master inside width x height, centred on transparency.

    Screens that cannot blend alpha (or only show 64 colours) dither soft edges
    and off-palette colours into speckle, so for them the icon is flattened onto
    black (the glance and launcher background) with a hard alpha edge, and for
    64-colour screens every channel is snapped to the palette.
    """
    side = min(width, height)
    icon = master.resize((side, side), Image.LANCZOS)
    canvas = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    canvas.paste(icon, ((width - side) // 2, (height - side) // 2))
    if mode == "full":
        return canvas
    pixels = canvas.load()
    for y in range(height):
        for x in range(width):
            red, green, blue, alpha = pixels[x, y]
            if alpha < 90:
                pixels[x, y] = (0, 0, 0, 0)
                continue
            if mode == "p64":
                if alpha < 128:
                    pixels[x, y] = (0, 0, 0, 0)
                    continue
                # One flat palette colour: blending edge pixels into the
                # palette would give a two-tone outline.
                red, green, blue = snap(red), snap(green), snap(blue)
            else:
                red, green, blue = (channel * alpha // 255 for channel in (red, green, blue))
            pixels[x, y] = (red, green, blue, 255)
    return canvas


def label(size):
    suffix = "" if size[2] == "full" else "-" + size[2]
    return f"{size[0]}x{size[1]}{suffix}"


shutil.rmtree(OUT, ignore_errors=True)
for size in sorted(sizes):
    folder = OUT / label(size)
    folder.mkdir(parents=True)
    render(*size).save(folder / "launcher_icon.png", optimize=True)
    (folder / "resources.xml").write_text(
        '<resources>\n    <bitmaps>\n'
        '        <bitmap id="LauncherIcon" filename="launcher_icon.png" />\n'
        '    </bitmaps>\n</resources>\n')

lines = [BEGIN]
for size in sorted(sizes):
    lines.append(f"# {label(size)}")
    for product in sorted(sizes[size]):
        paths = ["$(base.resourcePath)"] + EXTRA.get(product, []) + [f"resources-icons/{label(size)}"]
        lines.append(f"{product}.resourcePath = {';'.join(paths)}")
lines.append(END)
block = "\n".join(lines)

for jungle in JUNGLES:
    text = jungle.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if pattern.search(text):
        text = pattern.sub(lambda _: block, text)
    else:
        # Replace the hand-written fenix847mm line; its folders are in EXTRA.
        text = re.sub(r"^fenix847mm\.resourcePath.*$", lambda _: block, text, flags=re.M)
    jungle.write_text(text.rstrip("\n") + "\n")

print(f"{len(products)} products, sizes {[label(s) for s in sorted(sizes)]}")
